# ─── Sweep loop ───────────────────────────────────────────────────────────────
RUN_NUM=0
declare -A RUN_STATUS
CURRENT_BACKEND=""

for BACKEND in "${BACKEND_ARRAY[@]}"; do
    # Switch tokenizer backend at the start of each new backend group
    if [[ "$BACKEND" != "$CURRENT_BACKEND" ]]; then
        CURRENT_BACKEND="$BACKEND"
        if [[ "$MODE" == "k8s" ]]; then
            if [[ -n "$DGD_NAME" ]]; then
                dgd_switch_backend "$BACKEND"
            else
                k8s_switch_backend "$BACKEND"
            fi
        fi
    fi

    for CONC in "${CONCURRENCY_ARRAY[@]}"; do
        CONSECUTIVE_FAILS=0
        for ISL in "${ISL_ARRAY[@]}"; do
            RUN_NUM=$(( RUN_NUM + 1 ))
            KEY="${BACKEND}:${CONC}:${ISL}"
            if [[ "$SWEEP_CONCURRENCY" == true ]]; then
                RUN_DIR="${OUTPUT_DIR}/${BACKEND}_c${CONC}_isl${ISL}"
            else
                RUN_DIR="${OUTPUT_DIR}/${BACKEND}_isl${ISL}"
            fi

            # Skip remaining ISLs after N consecutive failures at this concurrency.
            # Higher ISLs are more demanding and will almost certainly also fail.
            if [[ $CONSECUTIVE_FAILS -ge $MAX_CONSECUTIVE_FAILS ]]; then
                RUN_STATUS[$KEY]="skipped"
                echo "  Run ${RUN_NUM}/${TOTAL_RUNS}: SKIPPED backend=${BACKEND} c=${CONC} ISL=${ISL}"
                echo "    (${CONSECUTIVE_FAILS} consecutive failures — skipping remaining ISLs at c=${CONC})"
                continue
            fi

            echo "═══════════════════════════════════════════════════════════"
            echo "  Run ${RUN_NUM}/${TOTAL_RUNS}: backend=${BACKEND}  concurrency=${CONC}  ISL=${ISL}"
            echo "  Output: ${RUN_DIR}"
            echo "═══════════════════════════════════════════════════════════"

            if [[ "$MODE" == "local" ]]; then
                # Wait for frontend port to free up from previous run
                PORT_WAIT=0
                while ss -tlnp 2>/dev/null | grep -q ":${FRONTEND_PORT} " || \
                      nc -z localhost "$FRONTEND_PORT" 2>/dev/null; do
                    [[ $PORT_WAIT -eq 0 ]] && echo "  Waiting for port ${FRONTEND_PORT} to free..."
                    sleep 1; PORT_WAIT=$(( PORT_WAIT + 1 ))
                    if [[ $PORT_WAIT -ge 30 ]]; then
                        echo "  Forcing port release..."
                        fuser -k "${FRONTEND_PORT}/tcp" 2>/dev/null || true
                        sleep 2; break
                    fi
                done

                RUN_ARGS=(
                    --isl "$ISL"
                    --concurrency "$CONC"
                    --output-dir "$RUN_DIR"
                )
                # Pass load-control flags that were provided; omit those that weren't
                # so run_perf.sh can apply its own defaults.  This mirrors the logic
                # in k8s_run_aiperf() so local and k8s runs behave identically.
                [[ -n "$NUM_REQUESTS" ]]       && RUN_ARGS+=(--num-requests "$NUM_REQUESTS")
                [[ -n "$BENCHMARK_DURATION" ]] && RUN_ARGS+=(--benchmark-duration "$BENCHMARK_DURATION")
                [[ -n "$WARMUP_DURATION" ]]    && RUN_ARGS+=(--warmup-duration "$WARMUP_DURATION")
                [[ -n "$WARMUP_COUNT" ]]       && RUN_ARGS+=(--warmup-count "$WARMUP_COUNT")
                [[ "$BACKEND" == "fast" ]]     && RUN_ARGS+=(--fast-tokens)

                setsid "${SCRIPT_DIR}/run_perf.sh" \
                    "${RUN_ARGS[@]}" "${PASSTHROUGH_ARGS[@]+"${PASSTHROUGH_ARGS[@]}"}" &
                CHILD_PID=$!

                if wait "$CHILD_PID" 2>/dev/null; then
                    RUN_STATUS[$KEY]="ok"
                    CONSECUTIVE_FAILS=0
                    echo "  Run ${RUN_NUM}/${TOTAL_RUNS}: SUCCESS"
                else
                    RC=$?
                    RUN_STATUS[$KEY]="fail"
                    CONSECUTIVE_FAILS=$(( CONSECUTIVE_FAILS + 1 ))
                    if [[ "$SWEEP_INTERRUPTED" == true ]]; then
                        echo "  Sweep interrupted."; break 3
                    fi
                    echo "  WARNING: Run ${RUN_NUM}/${TOTAL_RUNS} FAILED (rc=$RC) [consecutive failures: ${CONSECUTIVE_FAILS}/${MAX_CONSECUTIVE_FAILS}]"
                fi
                CHILD_PID=""

            else
                # K8s: run aiperf directly (frontend already patched for this backend).
                # Optionally restart the frontend pod to reset Prometheus counters,
                # then wait for frontend + all mocker workers before running aiperf.
                if [[ "$RESTART_FRONTEND" == true ]]; then
                    dgd_restart_frontend
                else
                    dgd_wait_all_ready 60
                fi

                # Capture pre-run frontend metrics (counters reset to zero if restarted)
                k8s_capture_metrics "${RUN_DIR}/frontend_metrics_pre.txt"

                if k8s_run_aiperf "${RUN_DIR}/aiperf" "$CONC" "$ISL"; then
                    RUN_STATUS[$KEY]="ok"
                    CONSECUTIVE_FAILS=0
                    echo "  Run ${RUN_NUM}/${TOTAL_RUNS}: SUCCESS"
                else
                    RUN_STATUS[$KEY]="fail"
                    CONSECUTIVE_FAILS=$(( CONSECUTIVE_FAILS + 1 ))
                    echo "  WARNING: Run ${RUN_NUM}/${TOTAL_RUNS} FAILED [consecutive failures: ${CONSECUTIVE_FAILS}/${MAX_CONSECUTIVE_FAILS}]"
                fi

                # Capture post-run frontend metrics (delta vs pre = this run only)
                k8s_capture_metrics "${RUN_DIR}/frontend_metrics_post.txt"
            fi
            echo ""
        done
    done
done

