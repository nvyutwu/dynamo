# Unified tokenizer-backend sweep — hf vs fast across ISL × concurrency.
#
# === LOCAL MODE (default) ===
# Starts etcd + NATS once; delegates each (backend, concurrency, ISL) run to
# run_perf.sh, which starts mocker + frontend per run with full observability
# (nsys, perf, flamegraph, Prometheus).
#
# Usage:
#   ./sweep.sh --model Qwen/Qwen3-0.6B [--isl-list 512,1024,2048]
#   ./sweep.sh --model Qwen/Qwen3-0.6B --backends fast --skip-nsys --skip-bpf
#
# === K8S MODE ===
# Expects mocker + frontend already deployed in k8s (via k8s_deploy.sh or
# --deploy). Patches DYN_TOKENIZER on the frontend Deployment between
# backends, waits for rollout + model readiness, then runs aiperf directly.
#
# Usage:
#   ./sweep.sh --mode k8s [--namespace dynamo-bench] [--endpoint frontend:8000]
#
# DGD mode (DynamoGraphDeployment — no plain Deployments):
#   ./sweep.sh --mode k8s --dgd-name dynamo-bench-mocker \
#              --namespace dynamo-bench --endpoint dynamo-bench-mocker-frontend:8000
#   (patches the DGD spec to toggle DYN_TOKENIZER; the Grove operator
#    recreates the frontend pod automatically)
#
# Deploy infra then sweep in one command:
#   ./sweep.sh --mode k8s --deploy --image dynamo:sglang-fast-tokens
#
# Cleanup k8s infra:
#   ./sweep.sh --mode k8s --cleanup
#
# Error-skip: after N consecutive ISL failures at a concurrency level,
# remaining ISLs are skipped (higher ISLs are more demanding).
# Default N=2; tune with --max-consecutive-fails N.
#
# Generate ConfigMap (for k8s Job via perf.yaml):
#   ./sweep.sh --create-configmap | kubectl apply -f -
#   kubectl apply -f benchmarks/frontend/scripts/perf.yaml

# ─── --create-configmap: early exit, must run before set -euo ────────────────
if [[ "${1:-}" == "--create-configmap" ]]; then
    cat <<'YAML_HEADER'
# Generated by: ./benchmarks/frontend/scripts/sweep.sh --create-configmap
# Regenerate: ./sweep.sh --create-configmap | kubectl apply -f -
apiVersion: v1
kind: ConfigMap
metadata:
  name: dynamo-bench-sweep-script
  namespace: dynamo-bench
data:
  sweep.sh: |
YAML_HEADER
    sed 's/^/    /' "$0"
    exit 0
fi

set -euo pipefail
ulimit -n 65536 2>/dev/null || ulimit -n 8192 2>/dev/null || true

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
REPO_ROOT="${SCRIPT_DIR}/../../.."

# ─── Defaults ────────────────────────────────────────────────────────────────
MODE="local"
MODEL="Qwen/Qwen3-0.6B"
MODEL_NAME=""
ISL_LIST="512,1024,2048"
BACKENDS="hf,fast"
CONCURRENCY_LIST="50,100,200"
NUM_REQUESTS=""
OSL="256"
OUTPUT_DIR=""
HF_TOKEN=""
WARMUP_COUNT=""           # Per-run warmup requests; defaults to concurrency if unset
BENCHMARK_DURATION="60"   # Minimum run duration in seconds (aiperf --benchmark-duration)
WARMUP_DURATION=""        # Warmup phase duration in seconds (aiperf --warmup-duration)
RESTART_FRONTEND=false # Restart the frontend pod before each run to reset Prometheus counters
MAX_CONSECUTIVE_FAILS=2  # Skip remaining ISLs after N consecutive failures per (backend, concurrency)
EXPORT_LEVEL="summary"   # aiperf --export-level: summary (small) | records (+ .jsonl) | raw (+ _raw.jsonl)

# K8s mode
NAMESPACE="dynamo-bench"
ENDPOINT="frontend:8000"
DEPLOY=false
CLEANUP=false
DGD_NAME=""   # When set, switch backends via kubectl patch dgd (not deployment)

# K8s deploy options (forwarded to k8s_deploy.sh when --deploy)
IMAGE=""
WORKERS=""
SPEEDUP_RATIO=""
REQUEST_PLANE=""
EVENT_PLANE=""
ENABLE_NVTX=false
IMAGE_PULL_SECRET=""

# Local mode: tracked separately so port-wait doesn't need to scan PASSTHROUGH_ARGS
FRONTEND_PORT=8000

# Passthrough args forwarded to run_perf.sh in local mode
PASSTHROUGH_ARGS=()

# ─── Argument parsing ────────────────────────────────────────────────────────
while [[ $# -gt 0 ]]; do
    case $1 in
        --mode)             MODE="$2"; shift 2 ;;
        # Common sweep options
        --model)            MODEL="$2"; PASSTHROUGH_ARGS+=(--model "$2"); shift 2 ;;
        --model-name)       MODEL_NAME="$2"; PASSTHROUGH_ARGS+=(--model-name "$2"); shift 2 ;;
        --isl-list)         ISL_LIST="$2"; shift 2 ;;
        --backends)         BACKENDS="$2"; shift 2 ;;
        --concurrency-list) CONCURRENCY_LIST="$2"; shift 2 ;;
        --num-requests)     NUM_REQUESTS="$2"; shift 2 ;;
        --osl)              OSL="$2"; PASSTHROUGH_ARGS+=(--osl "$2"); shift 2 ;;
        --output-dir)       OUTPUT_DIR="$2"; shift 2 ;;
        --hf-token)         HF_TOKEN="$2"; shift 2 ;;
        --warmup-count)     WARMUP_COUNT="$2"; shift 2 ;;
        --benchmark-duration) BENCHMARK_DURATION="$2"; shift 2 ;;
        --warmup-duration)  WARMUP_DURATION="$2"; shift 2 ;;
        --restart-frontend) RESTART_FRONTEND=true; shift ;;
        --max-consecutive-fails) MAX_CONSECUTIVE_FAILS="$2"; shift 2 ;;
        --export-level)     EXPORT_LEVEL="$2"; shift 2 ;;
        # K8s mode
        --namespace)        NAMESPACE="$2"; shift 2 ;;
        --endpoint)         ENDPOINT="$2"; shift 2 ;;
        --dgd-name)         DGD_NAME="$2"; shift 2 ;;
        --deploy)           DEPLOY=true; shift ;;
        --cleanup)          CLEANUP=true; shift ;;
        # K8s deploy options (also forwarded to k8s_deploy.sh)
        --image)            IMAGE="$2"; shift 2 ;;
        --enable-nvtx)      ENABLE_NVTX=true; shift ;;
        --image-pull-secret) IMAGE_PULL_SECRET="$2"; shift 2 ;;
