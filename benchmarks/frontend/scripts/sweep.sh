        --speedup-ratio)    SPEEDUP_RATIO="$2"; PASSTHROUGH_ARGS+=(--speedup-ratio "$2"); shift 2 ;;
        --request-plane)    REQUEST_PLANE="$2"; PASSTHROUGH_ARGS+=(--request-plane "$2"); shift 2 ;;
        --event-plane)      EVENT_PLANE="$2";   PASSTHROUGH_ARGS+=(--event-plane "$2"); shift 2 ;;
        --frontend-port)    FRONTEND_PORT="$2"; PASSTHROUGH_ARGS+=(--frontend-port "$2"); shift 2 ;;
        # Local passthrough flags (no value)
        --skip-bpf|--skip-nsys|--skip-flamegraph|--skip-perf|--tcpdump)
