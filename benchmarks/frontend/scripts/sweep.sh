[[ "$MODE" == "k8s" ]] && echo "Restart frontend before each run: $RESTART_FRONTEND"
echo ""

# ─── K8s functions ───────────────────────────────────────────────────────────
k8s_wait_ready() {
    local max_wait="${1:-300}"
    echo "  Waiting for model '$MODEL_NAME' at http://$ENDPOINT/v1/models..."
    local waited=0
    while ! curl -sf "http://$ENDPOINT/v1/models" 2>/dev/null | \
          jq -e --arg m "$MODEL_NAME" '.data[]? | select(.id == $m)' >/dev/null 2>&1; do
        sleep 5; waited=$(( waited + 5 ))
        if [[ $waited -ge $max_wait ]]; then
            echo "ERROR: Model not ready after ${max_wait}s" >&2
            curl -sf "http://$ENDPOINT/v1/models" 2>/dev/null || true
            return 1
        fi
        echo "  Still waiting (${waited}s / ${max_wait}s)..."
    done
    echo "  Model ready (waited ${waited}s)"
}

k8s_switch_backend() {
    local backend="$1"
    echo ""
    echo "--- Switching tokenizer backend → $backend ---"

    # Ensure we have a local HF cache BEFORE pausing the mocker.
    # The local cache is used to seed the new frontend pod later.
    LOCAL_HF_CACHE="${HF_HUB_CACHE:-${HOME}/.cache/huggingface/hub}"
    if [[ ! -d "$LOCAL_HF_CACHE" ]]; then
        echo "  Seeding local HF cache from cluster pods (before backend switch)..."
        mkdir -p "$(dirname "$LOCAL_HF_CACHE")"
        for _src_label in "app=frontend" "app=mocker"; do
            _SRC=$(kubectl -n "$NAMESPACE" get pod -l "$_src_label" \
                -o jsonpath='{.items[0].metadata.name}' 2>/dev/null)
            [[ -z "$_SRC" ]] && continue
            if kubectl -n "$NAMESPACE" exec "$_SRC" -- \
                    test -d /home/dynamo/.cache/huggingface/hub 2>/dev/null; then
                kubectl -n "$NAMESPACE" exec "$_SRC" -- \
                    tar cf - --dereference -C /home/dynamo/.cache/huggingface hub 2>/dev/null \
                | tar xf - -C "$(dirname "$LOCAL_HF_CACHE")" 2>/dev/null \
                && { echo "  Local cache seeded from $_src_label OK"; break; } \
                || echo "  WARNING: seed from $_src_label failed"
            fi
        done
        [[ -d "$LOCAL_HF_CACHE" ]] || echo "  WARNING: could not seed local HF cache"
    fi

    # Scale mocker to 0 so no discovery events fire while frontend restarts
    # with an empty cache. Brought back up after cache is seeded.
    echo "  Pausing mocker to prevent premature discovery events..."
    kubectl -n "$NAMESPACE" scale deployment/mocker --replicas=0 2>/dev/null || true
    kubectl -n "$NAMESPACE" rollout status deployment/mocker --timeout=60s 2>/dev/null || true

    # Patch frontend backend + ensure HF offline mode (HF is typically blocked in cluster)
    # Map sweep-level backend name to DYN_TOKENIZER env var value
    local dyn_tok_val
    case "$backend" in
        fast|fastokens) dyn_tok_val="fastokens" ;;
        hf|default|"")  dyn_tok_val="default" ;;
        *)               dyn_tok_val="$backend" ;;
    esac
    kubectl -n "$NAMESPACE" set env deployment/frontend \
        "DYN_TOKENIZER=$dyn_tok_val" "HF_HUB_OFFLINE=1"
    echo "  Waiting for frontend rollout..."
    kubectl -n "$NAMESPACE" rollout status deployment/frontend --timeout=300s

    # Seed the HF model cache into the new frontend pod from local cache.
    # Use tar so all files (resolved from symlinks via --dereference) are included.
    echo "  Seeding HF model cache → frontend pod..."
    FRONTEND_POD=$(kubectl -n "$NAMESPACE" get pod -l app=frontend \
        -o jsonpath='{.items[0].metadata.name}' 2>/dev/null)
    if [[ -n "$FRONTEND_POD" && -d "$LOCAL_HF_CACHE" ]]; then
        kubectl -n "$NAMESPACE" exec "$FRONTEND_POD" -- \
            mkdir -p /home/dynamo/.cache/huggingface 2>/dev/null || true
        # Note: dynamo container image may reject gzip streams via kubectl exec
        # (TLS bad MAC issues). Use uncompressed tar instead.
        tar cf - -C "$(dirname "$LOCAL_HF_CACHE")" hub 2>/dev/null \
        | kubectl -n "$NAMESPACE" exec -i "$FRONTEND_POD" -- \
            bash -c 'tar xf - -C /home/dynamo/.cache/huggingface && echo seeded' 2>/dev/null \
        && echo "  Cache seeded OK" \
        || echo "  WARNING: frontend cache seed failed"
    else
        echo "  WARNING: no local HF cache — frontend may fail model registration"
    fi

    # Bring mocker back up; it will re-register in etcd, triggering the
    # frontend discovery watcher which now finds a warm local cache.
    echo "  Resuming mocker..."
    kubectl -n "$NAMESPACE" scale deployment/mocker --replicas=1 2>/dev/null || true
    kubectl -n "$NAMESPACE" rollout status deployment/mocker --timeout=120s 2>/dev/null || true

    k8s_wait_ready 300
}

# dgd_switch_backend: switch tokenizer backend on a DynamoGraphDeployment.
# DGD pods are managed directly by the Grove operator (no Deployment objects).
# We patch the DGD spec; the operator recreates the frontend pod.
#
# Pod label selector: nvidia.com/dynamo-graph-deployment-name=<dgd-name>
#                     nvidia.com/dynamo-component-type=<type>
dgd_switch_backend() {
    local backend="$1"
    echo ""
    echo "--- Switching DGD tokenizer backend → $backend (dgd=$DGD_NAME) ---"

    # Map sweep-level backend name to DYN_TOKENIZER env var value
    local dyn_tok_val
    case "$backend" in
        fast|fastokens) dyn_tok_val="fastokens" ;;
        hf|default|"")  dyn_tok_val="default" ;;
        *)               dyn_tok_val="$backend" ;;
    esac

    # Find the index of DYN_TOKENIZER in the Frontend env array
    local idx
    idx=$(kubectl get dgd "$DGD_NAME" -n "$NAMESPACE" -o json 2>/dev/null | \
        jq '.spec.services.Frontend.extraPodSpec.mainContainer.env |
            to_entries[] | select(.value.name == "DYN_TOKENIZER") | .key' 2>/dev/null || true)

    if [[ -n "$idx" ]]; then
        kubectl patch dgd "$DGD_NAME" -n "$NAMESPACE" --type=json \
            -p="[{\"op\":\"replace\",\"path\":\"/spec/services/Frontend/extraPodSpec/mainContainer/env/${idx}/value\",\"value\":\"$dyn_tok_val\"}]"
    else
        # Env var not present yet — add it
        kubectl patch dgd "$DGD_NAME" -n "$NAMESPACE" --type=json \
            -p="[{\"op\":\"add\",\"path\":\"/spec/services/Frontend/extraPodSpec/mainContainer/env/-\",\"value\":{\"name\":\"DYN_TOKENIZER\",\"value\":\"$dyn_tok_val\"}}]"
    fi
    echo "  DGD patched — waiting for frontend pod replacement..."

    # Record current frontend pod name so we can wait for it to disappear
    local old_pod
    old_pod=$(kubectl -n "$NAMESPACE" get pod \
        -l "nvidia.com/dynamo-graph-deployment-name=${DGD_NAME},nvidia.com/dynamo-component-type=frontend" \
        -o jsonpath='{.items[0].metadata.name}' 2>/dev/null || true)

    if [[ -n "$old_pod" ]]; then
        echo "  Waiting for old pod $old_pod to terminate..."
        local waited=0
        while kubectl -n "$NAMESPACE" get pod "$old_pod" >/dev/null 2>&1; do
            sleep 5; waited=$(( waited + 5 ))
            [[ $waited -ge 120 ]] && echo "  WARNING: old pod still present after 120s" && break
        done
    fi

    # Wait for new frontend pod to be Ready, then all workers, then model endpoint
    echo "  Waiting for new frontend pod to be Ready..."
    kubectl -n "$NAMESPACE" wait pod \
        -l "nvidia.com/dynamo-graph-deployment-name=${DGD_NAME},nvidia.com/dynamo-component-type=frontend" \
        --for=condition=Ready --timeout=300s

    dgd_wait_all_ready 300
}

k8s_capture_metrics() {
    local dest="$1"
    mkdir -p "$(dirname "$dest")"
    if curl -sf "http://$ENDPOINT/metrics" > "$dest" 2>/dev/null; then
        echo "  Metrics captured → $dest ($(wc -l < "$dest") lines)"
    else
        echo "  WARNING: could not capture metrics from http://$ENDPOINT/metrics"
        echo "# metrics capture failed at $(date -Iseconds)" > "$dest"
    fi
}

# Wait for the frontend /v1/models endpoint AND all DGD worker pods to be Ready.
# In DGD mode the mocker workers register via etcd/NATS; the model endpoint
# only becomes available after at least one worker has registered.
dgd_wait_all_ready() {
    local max_wait="${1:-300}"

    if [[ -n "$DGD_NAME" ]]; then
        echo "  Waiting for all MockerWorker pods to be Ready..."
        kubectl -n "$NAMESPACE" wait pod \
            -l "nvidia.com/dynamo-graph-deployment-name=${DGD_NAME},nvidia.com/dynamo-component-type=worker" \
            --for=condition=Ready --timeout="${max_wait}s"
    fi

    k8s_wait_ready "$max_wait"
}

# Restart (delete) the frontend pod so that Prometheus counters reset to zero
# before the next aiperf run. The Grove operator recreates the pod automatically.
# Also waits for all worker pods to be Ready so no requests are dropped.
dgd_restart_frontend() {
    [[ -z "$DGD_NAME" ]] && return 0
    echo "  Restarting frontend pod to reset metrics counters..."

    local old_pod
    old_pod=$(kubectl -n "$NAMESPACE" get pod \
        -l "nvidia.com/dynamo-graph-deployment-name=${DGD_NAME},nvidia.com/dynamo-component-type=frontend" \
        -o jsonpath='{.items[0].metadata.name}' 2>/dev/null || true)

    if [[ -n "$old_pod" ]]; then
        kubectl delete pod "$old_pod" -n "$NAMESPACE" --grace-period=5 2>/dev/null
        echo "  Waiting for old pod $old_pod to terminate..."
        kubectl wait pod "$old_pod" -n "$NAMESPACE" \
            --for=delete --timeout=90s 2>/dev/null || true
    fi

    echo "  Waiting for new frontend pod to be Ready..."
    kubectl -n "$NAMESPACE" wait pod \
        -l "nvidia.com/dynamo-graph-deployment-name=${DGD_NAME},nvidia.com/dynamo-component-type=frontend" \
        --for=condition=Ready --timeout=300s

    dgd_wait_all_ready 300
}

k8s_run_aiperf() {
    local artifact_dir="$1" concurrency="$2" isl="$3"
    mkdir -p "$artifact_dir"

    # Build load-control args: prefer --benchmark-duration (time-based) over
    # --request-count (count-based) so each run gets a consistent measurement
    # window regardless of throughput.
    local load_args=()
    if [[ -n "$BENCHMARK_DURATION" ]]; then
        load_args+=(--benchmark-duration "$BENCHMARK_DURATION")
    fi
    if [[ -n "$NUM_REQUESTS" ]]; then
        load_args+=(--request-count "$NUM_REQUESTS")
    fi
    # If neither is set, default to request-count = concurrency * 20 (min 640)
    if [[ ${#load_args[@]} -eq 0 ]]; then
        local auto_count=$(( concurrency * 20 ))
        [[ "$auto_count" -lt 640 ]] && auto_count=640
        load_args+=(--request-count "$auto_count")
    fi

    # Warmup: prefer --warmup-duration, fall back to --warmup-request-count
    local warmup_args=()
    if [[ -n "$WARMUP_DURATION" ]]; then
        warmup_args+=(--warmup-duration "$WARMUP_DURATION")
    elif [[ -n "$WARMUP_COUNT" ]]; then
        warmup_args+=(--warmup-request-count "$WARMUP_COUNT")
    else
        warmup_args+=(--warmup-request-count "$concurrency")
    fi

    aiperf profile \
        --artifact-dir "$artifact_dir" \
        --model "$MODEL_NAME" \
        --endpoint-type chat \
        --endpoint /v1/chat/completions \
        --streaming \
        --url "http://$ENDPOINT" \
        --synthetic-input-tokens-mean "$isl" \
        --synthetic-input-tokens-stddev 0 \
        --output-tokens-mean "$OSL" \
        --output-tokens-stddev 0 \
        --extra-inputs "max_tokens:$OSL" \
        --extra-inputs "min_tokens:$OSL" \
        --extra-inputs "ignore_eos:true" \
        --extra-inputs "repetition_penalty:1.0" \
        --extra-inputs "temperature:0.0" \
        --concurrency "$concurrency" \
        "${load_args[@]}" \
        "${warmup_args[@]}" \
        --num-dataset-entries 12800 \
        --random-seed 100 \
        --workers-max "$concurrency" \
        --record-processors 32 \
        --export-level "$EXPORT_LEVEL" \
        --ui simple
}

# ─── Local functions ──────────────────────────────────────────────────────────
ETCD_PID=""; ETCD_DATA_DIR=""; NATS_PID=""

local_start_infra() {
    echo "--- Starting shared infrastructure ---"
    if ! curl -sf http://localhost:2379/health >/dev/null 2>&1; then
        command -v etcd >/dev/null 2>&1 || { echo "ERROR: etcd not found in PATH" >&2; exit 1; }
        ETCD_DATA_DIR=$(mktemp -d)
        etcd --data-dir="$ETCD_DATA_DIR" \
             --listen-client-urls=http://localhost:2379 \
             --advertise-client-urls=http://localhost:2379 \
             --listen-peer-urls=http://localhost:2380 \
             --initial-advertise-peer-urls=http://localhost:2380 \
             --initial-cluster=default=http://localhost:2380 \
             > /dev/null 2>&1 &
        ETCD_PID=$!
        for i in $(seq 1 30); do
            curl -sf http://localhost:2379/health >/dev/null 2>&1 && \
                { echo "  etcd ready (PID $ETCD_PID)"; break; }
            sleep 1
            [[ $i -eq 30 ]] && echo "ERROR: etcd failed to start after 30s" >&2 && exit 1
        done
    else
        echo "  etcd already running"
    fi

    if ! nc -z localhost 4222 2>/dev/null; then
        command -v nats-server >/dev/null 2>&1 || { echo "ERROR: nats-server not found in PATH" >&2; exit 1; }
        nats-server > /dev/null 2>&1 &
        NATS_PID=$!
        for i in $(seq 1 30); do
            nc -z localhost 4222 2>/dev/null && \
                { echo "  nats-server ready (PID $NATS_PID)"; break; }
            sleep 1
            [[ $i -eq 30 ]] && echo "ERROR: nats-server failed to start after 30s" >&2 && exit 1
        done
    else
        echo "  nats-server already running"
    fi
    echo ""
}

local_cleanup() {
    echo "--- Sweep cleanup ---"
    if [[ -n "$CHILD_PID" ]]; then
        kill -INT -- -"$CHILD_PID" 2>/dev/null || kill -INT "$CHILD_PID" 2>/dev/null || true
        for _w in 1 2 3 4 5; do kill -0 "$CHILD_PID" 2>/dev/null || break; sleep 1; done
        kill -9 -- -"$CHILD_PID" 2>/dev/null || kill -9 "$CHILD_PID" 2>/dev/null || true
    fi
    [[ -n "$ETCD_PID" ]] && { kill "$ETCD_PID" 2>/dev/null || true; sleep 1
        kill -9 "$ETCD_PID" 2>/dev/null || true
        [[ -n "$ETCD_DATA_DIR" ]] && rm -rf "$ETCD_DATA_DIR"; }
    [[ -n "$NATS_PID" ]] && { kill "$NATS_PID" 2>/dev/null || true; sleep 1
        kill -9 "$NATS_PID" 2>/dev/null || true; }
    echo "Cleanup complete."
}

# ─── Mode setup ───────────────────────────────────────────────────────────────
CHILD_PID=""
SWEEP_INTERRUPTED=false

sweep_interrupt() { SWEEP_INTERRUPTED=true; exit 130; }

if [[ "$MODE" == "local" ]]; then
    trap local_cleanup EXIT
    trap sweep_interrupt INT TERM
    # Pre-download model config to avoid mocker startup failures on the first run.
