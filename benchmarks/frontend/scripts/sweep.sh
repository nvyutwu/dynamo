**OSL**: ${OSL}

## Results

| Backend | Concurrency | ISL | Req/s | TTFT p50 (ms) | TTFT p99 (ms) | Output Tput (tok/s) | Tokenize Avg (ms) | Prefill Tput (tok/s) | Status |
|---------|-------------|-----|-------|---------------|---------------|---------------------|-------------------|----------------------|--------|
EOF

for BACKEND in "${BACKEND_ARRAY[@]}"; do
    for CONC in "${CONCURRENCY_ARRAY[@]}"; do
        for ISL in "${ISL_ARRAY[@]}"; do
            KEY="${BACKEND}:${CONC}:${ISL}"
            if [[ "$SWEEP_CONCURRENCY" == true ]]; then
                RUN_DIR="${OUTPUT_DIR}/${BACKEND}_c${CONC}_isl${ISL}"
            else
                RUN_DIR="${OUTPUT_DIR}/${BACKEND}_isl${ISL}"
            fi

            if [[ "${RUN_STATUS[$KEY]:-fail}" == "skipped" ]]; then
                echo "| ${BACKEND} | ${CONC} | ${ISL} | N/A | N/A | N/A | N/A | N/A | N/A | SKIPPED |" >> "$SUMMARY_FILE"
                continue
            fi

            if [[ "${RUN_STATUS[$KEY]:-fail}" != "ok" ]]; then
                echo "| ${BACKEND} | ${CONC} | ${ISL} | N/A | N/A | N/A | N/A | N/A | N/A | FAILED |" >> "$SUMMARY_FILE"
                continue
            fi

            # aiperf writes profile_export_aiperf.json with nested metric objects:
            #   .request_throughput.avg, .time_to_first_token.p50, etc.
            AIPERF_JSON="$RUN_DIR/aiperf/profile_export_aiperf.json"
            REQ_S="N/A"; TTFT_P50="N/A"; TTFT_P99="N/A"; OUT_TPUT="N/A"
            TOK_AVG="N/A"; PREFILL_TPUT="N/A"

            if [[ -f "$AIPERF_JSON" ]] && command -v jq &>/dev/null; then
                REQ_S=$(jq -r    '.request_throughput.avg        // "N/A"' "$AIPERF_JSON" 2>/dev/null)
                TTFT_P50=$(jq -r '.time_to_first_token.p50       // "N/A"' "$AIPERF_JSON" 2>/dev/null)
                TTFT_P99=$(jq -r '.time_to_first_token.p99       // "N/A"' "$AIPERF_JSON" 2>/dev/null)
                OUT_TPUT=$(jq -r '.output_token_throughput.avg   // "N/A"' "$AIPERF_JSON" 2>/dev/null)
                for _v in REQ_S TTFT_P50 TTFT_P99 OUT_TPUT; do
                    _val="${!_v}"
                    if [[ "$_val" =~ ^[0-9] ]]; then
                        printf -v "$_v" "%.2f" "$_val" 2>/dev/null || true
                    fi
                done
            fi

            # Tokenize avg and prefill throughput from Prometheus.
            # Available in local mode (run_perf.sh scrapes /metrics); N/A in k8s
            # where Prometheus scraping is not performed by the sweep script itself.
            PROM="$RUN_DIR/prometheus/final_snapshot.txt"
            if [[ -f "$PROM" ]]; then
                TOK_SUM=$(grep -m1 'dynamo_frontend_tokenize_seconds_sum'   "$PROM" 2>/dev/null | awk '{print $2}' || echo "")
                TOK_CNT=$(grep -m1 'dynamo_frontend_tokenize_seconds_count' "$PROM" 2>/dev/null | awk '{print $2}' || echo "")
                if [[ -n "$TOK_SUM" && -n "$TOK_CNT" && "$TOK_CNT" != "0" ]]; then
                    TOK_AVG=$(awk "BEGIN {printf \"%.3f\", ($TOK_SUM / $TOK_CNT) * 1000}" 2>/dev/null || echo "N/A")
                fi
                PFILL_TOKENS=$(grep -m1 'dynamo_prefill_tokens_total'         "$PROM" 2>/dev/null | awk '{print $2}' || echo "")
                PFILL_TIME=$(grep -m1   'dynamo_prefill_duration_seconds_sum' "$PROM" 2>/dev/null | awk '{print $2}' || echo "")
                if [[ -n "$PFILL_TOKENS" && -n "$PFILL_TIME" && "$PFILL_TIME" != "0" ]]; then
                    PREFILL_TPUT=$(awk "BEGIN {printf \"%.0f\", $PFILL_TOKENS / $PFILL_TIME}" 2>/dev/null || echo "N/A")
                fi
            fi

            echo "| ${BACKEND} | ${CONC} | ${ISL} | ${REQ_S} | ${TTFT_P50} | ${TTFT_P99} | ${OUT_TPUT} | ${TOK_AVG} | ${PREFILL_TPUT} | OK |" >> "$SUMMARY_FILE"
        done
    done
done

