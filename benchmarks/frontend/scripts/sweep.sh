        [[ -n "$HF_TOKEN" ]] && _HF_TOKEN_ARGS=(--token "$HF_TOKEN")
        if ! huggingface-cli download "$MODEL" --include "config.json" \
                "${_HF_TOKEN_ARGS[@]}" 2>/dev/null; then
            echo "  WARNING: Failed to download config.json for $MODEL (may already be cached)"
        else
            echo "  Model config cached for $MODEL"
        fi
        echo ""
    fi
    local_start_infra
else
    # K8s: optionally deploy infrastructure first
    if [[ "$DEPLOY" == true ]]; then
        echo "--- Deploying k8s infrastructure ---"
        DEPLOY_ARGS=(--namespace "$NAMESPACE")
        [[ -n "$IMAGE" ]]            && DEPLOY_ARGS+=(--image "$IMAGE")
        [[ -n "$MODEL" ]]            && DEPLOY_ARGS+=(--model "$MODEL")
