echo "Total runs:   $TOTAL_RUNS"
echo "Max consec. fails: $MAX_CONSECUTIVE_FAILS (skip remaining ISLs after this many)"
echo "Output:       $OUTPUT_DIR"
[[ "$MODE" == "k8s" ]] && echo "Namespace:    $NAMESPACE" && echo "Endpoint:     $ENDPOINT"
