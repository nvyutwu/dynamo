# ─── Output directory ────────────────────────────────────────────────────────
TIMESTAMP=$(date +%Y%m%d_%H%M%S)
if [[ -z "$OUTPUT_DIR" ]]; then
    if [[ "$MODE" == "k8s" ]]; then
        OUTPUT_DIR="/artifacts/sweep_${TIMESTAMP}"
    else
        OUTPUT_DIR="${REPO_ROOT}/artifacts/sweep_${TIMESTAMP}"
    fi
fi
mkdir -p "$OUTPUT_DIR"

TOTAL_RUNS=$(( ${#BACKEND_ARRAY[@]} * ${#CONCURRENCY_ARRAY[@]} * ${#ISL_ARRAY[@]} ))

# ─── Banner ──────────────────────────────────────────────────────────────────
echo "╔══════════════════════════════════════════════════════════════╗"
echo "║          Tokenizer Backend Sweep                            ║"
echo "╚══════════════════════════════════════════════════════════════╝"
echo ""
echo "Mode:         $MODE"
echo "Model:        $MODEL"
echo "Backends:     $BACKENDS"
echo "ISL values:   $ISL_LIST"
echo "Concurrency:  $CONCURRENCY_LIST"
echo "Requests/run: ${NUM_REQUESTS:-auto}"
echo "Duration/run: ${BENCHMARK_DURATION:-N/A}s"
